#!/usr/bin/env python3
r"""Generate third_party/tok_unicode_m.h: the Unicode mark ranges (category M*) that the
qwen35 pre-tokenizer regex uses ([\p{L}\p{M}]+). Same layout and lookup (uni_in) as
tok_unicode.h.

    python tools/gen_unicode_m.py > third_party/tok_unicode_m.h
"""
import sys
import unicodedata

ranges = []
start = None
for c in range(0x110000):
    m = unicodedata.category(chr(c)).startswith("M")
    if m and start is None:
        start = c
    if not m and start is not None:
        ranges.append((start, c - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))
out = sys.stdout
out.write("/* GENERATED by tools/gen_unicode_m.py from Python unicodedata %s, do not edit by hand.\n"
          " * uni_M = Mn + Mc + Me (marks), for the qwen35 pre-tokenizer. */\n" % unicodedata.unidata_version)
out.write("#ifndef TOK_UNICODE_M_H\n#define TOK_UNICODE_M_H\n#include <stdint.h>\n#include \"tok_unicode.h\"\n\n")
out.write("static const uint32_t uni_M[][2] = {\n")
for a, b in ranges:
    out.write("    {0x%X, 0x%X},\n" % (a, b))
out.write("};\nstatic const int uni_M_n = %d;\n" % len(ranges))
out.write("static inline int is_M(uint32_t c){ return uni_in(uni_M,uni_M_n,c); }\n\n#endif\n")
